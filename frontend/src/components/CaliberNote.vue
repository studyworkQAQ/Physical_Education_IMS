<script setup lang="ts">
/**
 * `CaliberNote.vue` —— 教师大屏面板底部那个「**ⓘ 口径**」的折叠说明块。
 *
 * ---------------------------------------------------------------------------
 * ⚠️ 它为什么存在（品牌与密度波）
 * ---------------------------------------------------------------------------
 * 大屏 8 个面板里原有 **5 块** `.bs-fine` 的开发者口径说明，CDP 实测合计
 * **489.6 px**（其中 3 块各占 86–144 px，占掉所在面板高度的 21%–28%）。
 * 它们是硬规矩 #39「如实记」的产物 —— 逐字交代「这个数是怎么算出来的、
 * 与后端哪一格对拍、哪两套阈值不得混用」，**一个字都不能删**（删了就是丢审计链）。
 * 但它们也**不是给投屏看的教师内容**：大屏是几米外读的，而这几段是 18px 的
 * 长句、还夹着 `code` 与后端字段名。用户 2026-10-12 的原话是
 * 「WEEK 数据水位这个板块的 UI 分布有点松散……页面部分存在留白的现象」，
 * 而这 5 块正是「松散感」的主要来源（本波用截图 + CDP 逐面板量过，见报告 §4）。
 *
 * 处置：把**默认可见的那一层**收进一个折叠，点开才显示全文；内容逐字不动。
 *
 * ---------------------------------------------------------------------------
 * ⚠️ 形态为什么是「折叠」，不是 tooltip、也不是页尾集中一节
 * ---------------------------------------------------------------------------
 *  · **tooltip 在投影上不可用**：大屏没有 hover（它是投在墙上的、教师站在讲台上），
 *    而 `:focus` 触发的 tooltip 在几米外也读不清；
 *  · **页尾集中一节**会把「这一格的口径」与「这一格」拆开：口径的价值恰恰在于它
 *    **挨着**它解释的那个数（审计时要能一眼对上「哪一句话在说哪一个数」），
 *    集中到页尾就变成了一份要来回翻的脚注表；
 *  · **`<details>`** 是原生的、**零 JS / 零依赖**的折叠：默认收起、可键盘操作
 *    （`<summary>` 天生是 focusable 的 button 语义）、有 `aria-expanded` 的等价语义，
 *    而且**收起时内容不渲染** —— 故 `smoke.mjs` 第 14 步的重叠守卫
 *    （TreeWalker + Range 逐行求交）对它取到 0 个矩形，不会因为它而报红。
 *
 * ---------------------------------------------------------------------------
 * ⚠️ 它**钉在面板底部**
 * ---------------------------------------------------------------------------
 * `.bs-cal { margin-block-start: auto }`。`.bs-grid` 自本波起是
 * `align-items: stretch`（同一排的面板等高），于是内容少的那一个面板会在底部
 * 留一个洞；把口径条钉在底部，那个洞就变成「卡片页脚之前的一段留白」——
 * 一个有边界的、看起来是有意的形状，而不是排版没做完。
 *
 * ⚠️ 用法（`Dashboard.vue` 的 5 个面板）：把原来 `<p class="bs-fine">…</p>` 里的
 *    **全部内容**原样放进默认插槽即可；条件显示的那一块（分层面板的周环比）
 *    把 `v-if` 挪到 `<CaliberNote>` 上。
 */
interface Props {
  /** 折叠条上那个词。⚠️ 缺省就是「口径」——本仓里它指的是「这个数是怎么算出来的」，
   *  不是「口径不明」。改这个词之前先想清楚它要不要跟 spec 里的用法保持一致。 */
  label?: string
}

withDefaults(defineProps<Props>(), { label: '口径' })
</script>

<template>
  <details class="bs-cal">
    <summary class="bs-cal__toggle">
      <span class="bs-cal__text">ⓘ {{ label }}</span>
    </summary>
    <div class="bs-cal__body">
      <slot />
    </div>
  </details>
</template>

