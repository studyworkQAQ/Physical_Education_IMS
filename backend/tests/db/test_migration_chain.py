def test_the_migration_chain_is_in_sync_with_the_models(tmp_path):
    """在 head 上跑 autogenerate 比较，**应当无 diff**。

    有 diff 只有一种解释：**有人改了 ``app/db/models/**`` 却没有写迁移**。
    修法见 spec §13.7：``alembic revision --autogenerate -m "..."`` → 人审那条迁移
    （⚠️ 尤其要审 ``JsonText`` 列的 import，见
    ``tests/db/test_migration_baseline.py`` 的模块 docstring）→ 本条转绿。

    ⚠️ 本条走的是**与生产完全相同**的那条路径：同一个 ``alembic.ini``、同一个
    ``migrations/env.py``、同一份 ``COMPARE_OPTS``（``compare_type=True`` /
    ``render_as_batch=True`` / ``compare_server_default=False`` /
    ``version_table``），只是把库 URL 通过 ``Config.attributes`` 交进去
    （:data:`app.db.session.DB_URL_ATTRIBUTE`）而不是读 ``PE_DB_URL``——
    于是它不依赖跑测试那个 shell 的环境变量。
    """
    url, eng = _upgrade_a_fresh_database(tmp_path / "sync.db")
    try:
        # command.check 在无 diff 时安静返回、有 diff 时抛 AutogenerateDiffsDetected
        command.check(_alembic_config(url))
    finally:
        eng.dispose()


def test_the_sync_guard_catches_a_column_the_model_has_and_the_database_does_not(tmp_path):
    """**定点变异 A**：库里少一列（= 模型有、迁移没跟上）→ 守卫必须红。

    ⚠️ 删的是 ``semester.is_current``：``semester`` 是 27 张表里唯一一张
    **既没有索引也没有 CHECK** 的表（实测），故 ``ALTER TABLE … DROP COLUMN``
    在 SQLite 上不会撞到「该列被索引/约束引用」那一档，变异因此是干净的。
    ⚠️ 期望侧是**字面量**（``semester`` / ``is_current``），不从模型读回来。
    """
    url, eng = _upgrade_a_fresh_database(tmp_path / "drift-column.db")
    try:
        with eng.begin() as conn:
            conn.execute(text("ALTER TABLE semester DROP COLUMN is_current"))

        with pytest.raises(AutogenerateDiffsDetected) as excinfo:
            command.check(_alembic_config(url))

        message = str(excinfo.value)
        assert "semester" in message and "is_current" in message, message
        assert "add_column" in message, message
    finally:
        eng.dispose()


def test_the_sync_guard_catches_a_dropped_index(tmp_path):
    """**定点变异 B**：库里少一个索引 → 守卫必须红。

    ⚠️ 与变异 A 不重叠：A 钉的是「列比较」，本条钉的是「索引比较」。
    少了本条，把 ``env.py`` 的索引比较关掉（或 ``render_as_batch`` 那一档改动
    顺带弄坏索引渲染）不会有任何测试红，而那会让 9 个 ``ix_*_batch_id``
    在甲方的库上悄悄消失——症状是「按 ``batch_id`` 查派生表变慢」，
    一个没有人会归因到迁移的失效。
    """
    url, eng = _upgrade_a_fresh_database(tmp_path / "drift-index.db")
    try:
        with eng.begin() as conn:
            conn.execute(text("DROP INDEX ix_alert_batch_id"))

        with pytest.raises(AutogenerateDiffsDetected) as excinfo:
            command.check(_alembic_config(url))

        message = str(excinfo.value)
        assert "ix_alert_batch_id" in message, message
        assert "add_index" in message, message
    finally:
        eng.dispose()


def test_the_guard_is_not_vacuous_because_the_chain_really_has_revisions():
    """空转守卫：迁移链**真的有**脚本，且它们真的能被 alembic 解析出修订号。

    ⚠️ 少了本条，``versions/`` 被搬空时上面三条会分别以「找不到文件」的样子红，
    而下一个人最容易做的「修」是把守卫删掉。本条把「链是空的」与「链不同步」
    报成两种不同的错。
    """
    scripts = _migration_scripts()
    assert len(scripts) >= 1, f"迁移链是空的: {VERSIONS_DIR}"
    revisions = [script.revision for script in ScriptDirectory(
        str(MIGRATIONS_DIR)).walk_revisions()]
    assert len(revisions) == len(scripts), (revisions, [p.name for p in scripts])


