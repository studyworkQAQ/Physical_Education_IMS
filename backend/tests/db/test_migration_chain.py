def test_the_migration_scripts_carry_no_data():
    """计划正文逐字要求的那一条：**基线里不带数据**。

    判据是 AST 级的两格：① 迁移脚本里不许调用 ``op.bulk_insert``（alembic 唯一的数据
    插入 op）也不许调用 ``op.execute``（唯一能跑任意 SQL 的口子）；
    ② **非 docstring** 的字符串常量，其**第一个词**不许是 ``INSERT`` / ``UPDATE`` /
    ``DELETE``。
    ⚠️ 两格都刻意不做子串搜索：迁移脚本的 docstring 会**提及**这些词（解释「为什么
    不带数据」），而提及不是本身（硬规矩 #109）；而子串搜索还会把 ``'updated_at'``
    这种**列名**判成一条 ``UPDATE`` 语句。按「第一个词」判则两者都不误伤。

    ⚠️ 为什么这一条值得单独钉：把演示数据塞进基线看起来很省事（「升级完甲方就有数据了」），
    而它的后果是**每一次** ``upgrade head`` 都会重灌一遍——甲方现场那份库里是一学期的
    真实数据，重灌就是覆盖。数据的所有者是 ``backend/scripts/demo_bootstrap.py``
    （演示）与三个 CLI（生产），不是迁移链。
    """
    offenders: list[str] = []
    for path in _migration_scripts():
        tree = ast.parse(path.read_text(encoding="utf-8"))
        for node in ast.walk(tree):
            if (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)
                    and isinstance(node.func.value, ast.Name)
                    and node.func.value.id == "op"
                    and node.func.attr in ("bulk_insert", "execute")):
                offenders.append(f"{path.name}:{node.lineno}: op.{node.func.attr}")
        for value in _string_constants(tree):
            head = value.strip().split(" ", 1)[0].upper()
            if head in ("INSERT", "UPDATE", "DELETE"):
                offenders.append(
                    f"{path.name}: 非 docstring 的字符串常量以 {head} 开头: {value[:60]!r}"
                )
    assert not offenders, "迁移脚本里带了数据：\n  " + "\n  ".join(offenders)


def test_alembic_ini_is_pure_ascii_and_carries_no_connection_string():
    """``alembic.ini`` 两格实测事实：纯 ASCII + ``sqlalchemy.url`` 恒为空。

    ① **纯 ASCII**：alembic 1.20.0 的 ``alembic.util.compat.read_config_parser`` 用
       ``encoding="locale"`` 读那个文件，本机 locale 是 GBK。实测（本 Task）：
       一行 UTF-8 中文注释就让**每一条** ``alembic`` 命令在启动期抛
       ``UnicodeDecodeError: 'gbk' codec can't decode byte 0x80 in position 30``
       ——包括 ``init_db`` 里那三次程序内调用，也就是**服务起不来**。
       ⚠️ 这一格的失效方向是「加了中文注释之后一切照旧，直到某天在甲方的
       GBK 机器上跑」，故必须有一条测试在开发机上就红。
    ② **``sqlalchemy.url`` 恒为空**：连接串的唯一所有者是 ``PE_DB_URL``
       （名字在 :data:`app.main.DB_URL_ENV_VAR`）与程序内传入的
       ``Config.attributes``。ini 里再写一份就是第二个所有者，
       而第二个所有者一定是相对路径的那一个（理由逐字在
       :func:`app.db.session.engine` 的 docstring 里）。
    """
    raw = ALEMBIC_INI.read_bytes()
    assert ALEMBIC_INI.is_file(), ALEMBIC_INI
    try:
        raw.decode("ascii")
    except UnicodeDecodeError as exc:
        raise AssertionError(
            f"alembic.ini 必须保持纯 ASCII（alembic 用 locale 编码 = 本机 GBK 读它）：{exc}"
        ) from exc
    assert raw[:3] != b"\xef\xbb\xbf", "alembic.ini 带 BOM"

    parser = configparser.ConfigParser()
    # 用 GBK 读一遍：这就是 alembic 自己的读法，能读通才算数。
    # ⚠️ ``raw=True`` 是承重的：``script_location`` 的值是 ``%(here)s/migrations``，
    #    而 configparser 的 BasicInterpolation 在 ``get()`` 时会去找一个叫 ``here``
    #    的键（alembic 自己会把它塞进 defaults），本测试不塞，故一律取原文。
    parser.read_string(raw.decode("gbk"))
    assert parser.get("alembic", "sqlalchemy.url", raw=True, fallback="<缺失>") == "", \
        "alembic.ini 里出现了连接串（唯一所有者是 PE_DB_URL / 程序内传入）"
    assert parser.get("alembic", "script_location", raw=True).endswith("migrations")


def test_the_migration_scripts_are_utf8_without_bom_and_parse():
    """``migrations/**`` 的 ``.py`` 一律 UTF-8 无 BOM 且可 ``ast.parse``。

    ⚠️ 这不是洁癖：``tests/architecture/test_layering.py`` 与
    ``tests/architecture/test_domain_purity.py`` 各有一段
    ``sorted(BACKEND.rglob("*.py"))`` + ``ast.parse(py.read_text(encoding="utf-8"))``
    的全仓扫描，``migrations/**`` 在扫描面内。一个 BOM 会让那两条守卫
    抛 ``SyntaxError``，而报错位置在**架构测试**里、真因在迁移脚本里。
    本条让真因报在真因上。
    """
    scripts = _migration_scripts() + [MIGRATIONS_DIR / "env.py"]
    assert len(scripts) >= 2, scripts
    for path in scripts:
        raw = path.read_bytes()
        assert raw[:3] != b"\xef\xbb\xbf", f"{path.name} 带 BOM"
        raw.decode("utf-8")  # UnicodeDecodeError 就是失败
        ast.parse(raw.decode("utf-8"))
        # ⚠️ 那两条架构守卫还会核对 ``_package_of(py) == py.parent.parts``；
        #    对 migrations/** 这等价于「不使用相对导入」（本目录不是包）。
        tree = ast.parse(raw.decode("utf-8"))
        relative = [node for node in ast.walk(tree)
                    if isinstance(node, ast.ImportFrom) and node.level]
        assert not relative, f"{path.name} 里有相对导入，而 migrations/ 不是包"
