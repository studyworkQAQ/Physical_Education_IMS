"""迁移链纪律：改了 ``app/db/models/**`` 就**必须**配一条迁移（Plan 06 Task 2）。

--------------------------------------------------------------------------
这条纪律要防的是什么
--------------------------------------------------------------------------

Plan 06 Task 1 之后，schema 有了**两个**所有者：模型（``app/db/models/**`` 里的
``Base.metadata``）与迁移链（``backend/migrations/versions/**``）。测试全部跑内存库、
走 ``create_all``，也就是说**测试看的是模型那一份**；而甲方现场那个磁盘库走的是
迁移链那一份。于是最省事的错误是这样发生的：

    给 student 加一列 → 跑全量测试 → 1340 条全绿（内存库已经有那一列了）→ 合并 →
    甲方升级 → 迁移链里没有那一列 → 端点在离真因很远的地方 500

**没有任何一条既有测试会红**，因为没有任何一条既有测试碰迁移链。本文件那一条
:func:`test_the_migration_chain_is_in_sync_with_the_models` 就是补这个洞的：
它把一个空库 ``upgrade head``、然后在 head 上跑一次 autogenerate 比较
（``alembic.command.check``），**应当无 diff**。有 diff = 有人改了模型没写迁移。

--------------------------------------------------------------------------
它为什么不是一条恒绿的守卫
--------------------------------------------------------------------------

``command.check`` 在两种情况下会「绿得没有意义」，两种都被本文件另外钉住：

* ``migrations/env.py`` 的 ``target_metadata`` 若是 ``None``（alembic 脚手架的缺省值），
  比较两侧有一侧是空的，于是**永远无 diff**。→
  :func:`test_the_sync_guard_catches_a_column_the_model_has_and_the_database_does_not`
  与 :func:`test_the_sync_guard_catches_a_dropped_index` 是两条**定点变异**：
  把建好的库改坏一格（删一列 / 删一个索引），守卫必须红。
  ⚠️ 它们走的是与真守卫**完全相同**的那条代码路径（同一个 ``command.check``、
  同一份 ``COMPARE_OPTS``），故它们红/绿直接说明真守卫有没有牙；
  这也顺手钉住了 ``env.py`` 的 ``compare_type`` / 索引比较两个开关没被关掉。
* ``migrations/versions/`` 若是空的，``upgrade head`` 什么也不建，``check`` 会把
  29 张表全报成 diff → 红（⚠️ 改前是 28，**Plan 08 Task 1** 加了 ``read_audit_log``）。这一档由
  ``tests/db/test_migration_baseline.py::test_the_chain_has_exactly_one_head_today`` 管。

--------------------------------------------------------------------------
本文件另外钉住三条「基线迁移的形状」
--------------------------------------------------------------------------

* :func:`test_the_migration_scripts_carry_no_data` —— 计划正文逐字要求
  「基线里不带数据」。判据是 AST 级的（不许出现 ``op.bulk_insert``、不许有非 docstring
  的字符串常量里含 ``INSERT``），不是文本搜索——⚠️ 文本搜索会把 docstring 里的
  **提及**当成**本身**（硬规矩 #109）。
* :func:`test_alembic_ini_is_pure_ascii_and_carries_no_connection_string` ——
  两格实测事实：① alembic 用 ``encoding="locale"``（本机 GBK）读那个 ini，
  一行 UTF-8 中文注释就让**每一条** ``alembic`` 命令在启动期 ``UnicodeDecodeError``；
  ② 连接串的唯一所有者是 ``PE_DB_URL`` / 程序内传入，ini 里那一行必须恒为空。
* :func:`test_the_migration_scripts_are_utf8_without_bom_and_parse` ——
  ``migrations/**`` 在 ``tests/architecture/`` 那两条 ``BACKEND.rglob("*.py")`` 守卫的
  AST 扫描面内，一个 BOM 或一处语法错误会让**那两条**守卫炸在很远的地方。

--------------------------------------------------------------------------
⚠️ Plan 06 Task 11 起：本文件还钉住「**改既有列**的那一条迁移」
⚠️ Plan 08 Task 1 起：本文件还钉住「**每一条加表迁移的 ``downgrade`` 真能跑**」
--------------------------------------------------------------------------

迁移 1/2/3 各**加一张表**，而加表的 ``downgrade`` 是 ``drop_table``——「回滚」与「数据」
在那三条上是同一件事。第四条（``0ac943e0da9b``，``login_attempt.login`` 的列宽
``VARCHAR(32)`` → ``VARCHAR(64)``）是**本链第一条改既有列**的迁移，而它走的是
``batch_alter_table``：SQLite 没有 ``ALTER COLUMN``，批处理的落地方式是
「建新表 → **拷数据** → 改名 → 删旧表」。⚠️ 于是「拷数据」那一格是一个**新的失效面**
（一个写坏的批处理在 ``upgrade`` 时不报错，症状是甲方现场升级完限流记录少了一半），
:func:`test_the_column_width_migration_round_trips_and_keeps_every_row` 因此
**先灌行、再走一整圈**（head → ``-1`` → head），逐字比行还在不在。
⚠️ **Plan 08 Task 1 把那条往返的 ``-1`` 改成了显式修订号**（``"7f3923d8af84"``）：
``-1`` 是**相对**的一步，链一长它就不再指向迁移 4 了（本波实测：加了迁移 5 之后
``-1`` 只删 ``read_audit_log``、``login`` 仍然是 ``VARCHAR(64)`` ⇒ 那条守卫会红在
与真因无关的地方）。逐字理由写在那个调用点上方的注释里。

--------------------------------------------------------------------------
⚠️ Plan 08 Task 1 起：每一条**加表**迁移的 ``downgrade`` 都要真跑一遍
--------------------------------------------------------------------------

计划 §1 第 5 条逐字要求「``downgrade`` 必须真能跑一遍并给取证」，理由是
Plan 06 Task 4 在迁移 4 上留过一个跑不通的 ``downgrade``（spec §15 C3）。
⚠️ 而「跑不通」那一档**不会被任何既有守卫抓到**：迁移 1/2/3/5 的 ``downgrade``
都是 ``drop_table``，而本波之前全仓**没有一条测试真的调过 ``command.downgrade``**
去走那一步（唯一那一条是迁移 4 的列宽往返）。
:func:`test_the_read_audit_log_migration_round_trips_and_keeps_every_other_row`
补的就是这一格，而它比迁移 4 那一条**多钉一件事**：
回滚**只许**删掉它自己建的那一张表（故本条往 ``audit_log`` 也灌一行、逐字比它还在）。
⚠️ **迁移 1/2/3 仍然没有各自的往返守卫**（如实记，硬规矩 #39）：它们的 ``downgrade``
是 alembic 自动生成的 ``drop_index`` + ``drop_table``，与迁移 5 逐字同形，
而迁移 5 那一条已经把这个形状跑通过一次。要给前三条各补一条的话是三次复制粘贴，
本波**刻意不做**（超出范围），已登记为待清扫。
"""
import ast
import configparser
import pathlib

import pytest
from alembic import command
from alembic.script import ScriptDirectory
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import create_engine, text

from app.config import BACKEND_DIR
from app.db.session import _alembic_config

#: ``backend/migrations/`` 与 ``backend/alembic.ini``。**字面路径**，不从
#: ``app.db.session.ALEMBIC_INI`` 读回来——那一侧是被测代码，两侧同源的话
#: 「有人把迁移链搬到别处、忘了改 session.py」这件事就抓不到了。
MIGRATIONS_DIR = BACKEND_DIR / "migrations"
VERSIONS_DIR = MIGRATIONS_DIR / "versions"
ALEMBIC_INI = BACKEND_DIR / "alembic.ini"


def _migration_scripts() -> list[pathlib.Path]:
    """``migrations/versions/`` 下的全部迁移脚本，按名字升序（报告顺序因此稳定）。"""
    # Path.rglob() / glob() 对不存在的目录静默返回空，缺这一行守卫会空转全绿
    assert VERSIONS_DIR.is_dir(), f"迁移目录缺失，守卫将空转全绿: {VERSIONS_DIR}"
    return sorted(VERSIONS_DIR.glob("*.py"))


def _string_constants(tree: ast.AST) -> list[str]:
    """一棵 AST 里**除 docstring 之外**的全部字符串常量（硬规矩 #109）。

    docstring 里写「基线不带数据」这句话是**提及**，不是**本身**；
    把它算进来会让一条诚实的注释把守卫弄红，而下一个人「修」它的办法是删注释。
    """
    docstrings: set[int] = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.ClassDef,
                             ast.FunctionDef, ast.AsyncFunctionDef)):
            first = node.body[0] if node.body else None
            if (isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant)
                    and isinstance(first.value.value, str)):
                docstrings.add(id(first.value))
    return [
        node.value
        for node in ast.walk(tree)
        if isinstance(node, ast.Constant) and isinstance(node.value, str)
        and id(node) not in docstrings
    ]


def _upgrade_a_fresh_database(path: pathlib.Path):
    """在 ``path`` 上跑一次 ``alembic upgrade head``，返回 ``(url, engine)``。"""
    url = "sqlite:///" + path.as_posix()
    command.upgrade(_alembic_config(url), "head")
    return url, create_engine(url)


